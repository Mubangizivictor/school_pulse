const PDFDocument = require('pdfkit');
const { renderOfficialStamp } = require('./stamp_renderer');

function escapeText(value, max = 300) { return String(value ?? '').replace(/[\r\n]+/g, ' ').trim().slice(0, max); }

function renderOfficialPdf(snapshot) {
  return new Promise((resolve, reject) => {
    const pdf = new PDFDocument({ size: 'A4', margin: 54, compress: false, info: { Title: snapshot.title, Subject: snapshot.documentNumber, Author: 'VictorBee Technologies' } });
    const buffers = [];
    pdf.on('data', (part) => buffers.push(part));
    pdf.on('end', () => resolve(Buffer.concat(buffers)));
    pdf.on('error', reject);
    const blue = '#1026A8';
    pdf.fillColor(blue).font('Helvetica-Bold').fontSize(21).text('SCHOOL PULSE');
    pdf.fillColor('#333333').font('Helvetica').fontSize(9).text('A VictorBee Technologies product | Kampala, Uganda');
    pdf.moveDown(2).fillColor(blue).font('Helvetica-Bold').fontSize(18).text(snapshot.title);
    pdf.moveDown(0.5).fillColor('#555555').font('Helvetica').fontSize(10)
      .text(`Official reference: ${snapshot.documentNumber}`)
      .text(`Issued: ${snapshot.issuedLabel}`);
    pdf.moveDown(1.5).strokeColor('#D7DCE8').lineWidth(1).moveTo(54, pdf.y).lineTo(541, pdf.y).stroke();
    pdf.moveDown(1);
    for (const row of snapshot.rows) {
      const [label, value] = Array.isArray(row) ? row : [row?.label, row?.value];
      if (!value) continue;
      const rowY = pdf.y;
      pdf.fillColor('#667085').font('Helvetica-Bold').fontSize(9).text(label.toUpperCase(), 54, rowY, { width: 155 });
      pdf.fillColor('#1D2939').font('Helvetica').fontSize(10).text(escapeText(value), 215, rowY, { width: 326 });
      pdf.y = Math.max(pdf.y, rowY + 24);
    }
    pdf.moveDown(1).fillColor('#344054').font('Helvetica').fontSize(10).text(snapshot.notice, { width: 470, lineGap: 3 });
    const stampY = Math.min(Math.max(pdf.y + 22, 560), 650);
    renderOfficialStamp(pdf, { x: 314, y: stampY, width: 205, dateLabel: snapshot.stampDate });
    pdf.fillColor('#667085').font('Helvetica').fontSize(8).text(
      'This official document was generated by School Pulse. For support, contact support@schoolpulse.victorbee.com.',
      54, 770, { width: 487, align: 'center' },
    );
    pdf.end();
  });
}

module.exports = { renderOfficialPdf };
