import 'package:flutter/material.dart';
import 'package:provider/provider.dart';

import 'package:school_pulse/design_system/app_components.dart';
import 'package:school_pulse/design_system/components/wizard_scaffold.dart';
import 'package:school_pulse/design_system/theme/app_colors.dart';

import '../add_staff_wizard_controller.dart';

const _previewChars = 'ABCDEFGHJKMNPQRSTUVWXYZabcdefghjkmnpqrstuvwxyz23456789';

class Step09LoginSecurity extends StatefulWidget {
  const Step09LoginSecurity({super.key});

  @override
  State<Step09LoginSecurity> createState() => _Step09LoginSecurityState();
}

class _Step09LoginSecurityState extends State<Step09LoginSecurity> {
  String _previewPassword = '';

  @override
  void initState() {
    super.initState();
    _regeneratePreview();
  }

  void _regeneratePreview() {
    final rand = DateTime.now().microsecondsSinceEpoch;
    setState(() {
      _previewPassword = List.generate(
        10,
        (i) => _previewChars[(rand + i * 31) % _previewChars.length],
      ).join();
    });
  }

  @override
  Widget build(BuildContext context) {
    final controller = context.watch<AddStaffWizardController>();
    final draft = controller.draft;

    return WizardScaffold(
      title: 'Add Staff Member',
      currentStep: stepNumberFor(WizardStep.loginSecurity),
      totalSteps: kWizardTotalSteps,
      onBack: () => controller.back(),
      footer: WizardFooterButtons(
        onBack: () => controller.back(),
        onNext: () => controller.next(),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          const WizardStepCaption(
            number: 9,
            title: 'Login & Security',
            subtitle: 'Set login credentials',
          ),
          const SizedBox(height: 16),
          TextFormField(
            enabled: false,
            initialValue: draft.email,
            decoration: const InputDecoration(
              labelText: 'Login Email',
              prefixIcon: Icon(Icons.email_outlined),
              helperText: 'Used as username',
            ),
          ),
          const SizedBox(height: 14),
          Row(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Expanded(
                child: TextFormField(
                  enabled: false,
                  initialValue: _previewPassword,
                  obscureText: true,
                  decoration: const InputDecoration(
                    labelText: 'Temporary Password',
                    prefixIcon: Icon(Icons.lock_outline),
                    helperText:
                        'The real password is generated securely on the server after Confirm.',
                  ),
                ),
              ),
              TextButton(
                onPressed: _regeneratePreview,
                child: const Text('Generate Now'),
              ),
            ],
          ),
          const SizedBox(height: 8),
          AlertBanner(
            title: 'Password shown after account creation',
            message:
                'For security, the actual temporary password is generated by the server and shown only once, on the Success screen.',
            color: AppColors.information(context),
          ),
          const SizedBox(height: 8),
          SwitchListTile(
            contentPadding: EdgeInsets.zero,
            title: const Text('Force Password Change'),
            subtitle: const Text(
              'User will be required to change password on first login',
            ),
            value: draft.forcePasswordChange,
            onChanged: (v) {
              draft.forcePasswordChange = v;
              controller.notifyDraftChanged();
            },
          ),
          SwitchListTile(
            contentPadding: EdgeInsets.zero,
            title: const Text('Send Login Details via Email'),
            value: draft.sendLoginDetailsViaEmail,
            onChanged: (v) {
              draft.sendLoginDetailsViaEmail = v;
              controller.notifyDraftChanged();
            },
          ),
        ],
      ),
    );
  }
}
