import 'package:flutter/material.dart';

enum ModuleCategory {
  core,
  academic,
  finance,
  operations,
  welfare,
  communication,
  identity,
  administration,
}

class ModuleDefinition {
  final String key, name, description;
  final ModuleCategory category;
  final IconData icon;
  final List<String> dependencies, requiredSetup;
  final bool sensitive, supportsDivisionScope, supportsCampusScope, beta;
  const ModuleDefinition({
    required this.key,
    required this.name,
    required this.description,
    required this.category,
    required this.icon,
    this.dependencies = const [],
    this.requiredSetup = const [],
    this.sensitive = false,
    this.supportsDivisionScope = false,
    this.supportsCampusScope = false,
    this.beta = false,
  });
}

