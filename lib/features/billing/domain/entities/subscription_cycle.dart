import 'package:equatable/equatable.dart';

/// Lifecycle of a single term's billing cycle. Phase 1
/// (functions/academic_calendar_billing.js: confirmAcademicCalendar) only
/// ever writes [upcoming] - every other value is defined now so Phase 2
/// (invoicing, reminders, suspension automation) can move a cycle through
/// them without a schema migration.
enum SubscriptionCycleStatus {
  upcoming,
  invoiced,
  paymentPending,
  paid,
  gracePeriod,
  overdue,
  suspended,
  cancelled,
  expired,
}

/// Payment status of a cycle, distinct from [SubscriptionCycleStatus].
/// Phase 1 only ever writes [unpaid] on generation.
enum SubscriptionCyclePaymentStatus { unpaid, paid, partial, waived }

/// An immutable-at-generation-time snapshot of the plan a cycle was billed
/// against. Never mutated after the cycle is created - if the school's plan
/// changes later, that only affects the *next* cycle generated, not this
/// historical record.
///
/// DEPRECATED as of Phase 3A/3C: plan-based billing has been replaced by
/// verified-student-count pricing bands (see [StudentPricingSnapshot]).
/// Cloud Functions no longer write `planSnapshot` on new cycles - kept here,
/// still nullable on [SubscriptionCycle], only so historical pre-Phase-3A
/// cycle docs remain readable.
class SubscriptionPlanSnapshot extends Equatable {
  final String planId;
  final String planName;
  final List<String> features;
  final double price;
  final String currency;

  const SubscriptionPlanSnapshot({
    required this.planId,
    required this.planName,
    required this.features,
    required this.price,
    required this.currency,
  });

  @override
  List<Object?> get props => [planId, planName, features, price, currency];
}

/// An immutable-at-generation-time snapshot of the pricing band a cycle was
/// billed against, taken from `student_pricing_bands`
/// (functions/student_pricing_bands.js). Introduced in Phase 3A, replacing
/// [SubscriptionPlanSnapshot] as the source of a cycle's price - price is
/// now determined solely by the school's verified enrolled student count at
/// generation time, not by a plan. Never mutated after the cycle is created.
class StudentPricingSnapshot extends Equatable {
  final String bandId;
  final int minStudents;

  /// Null means "unbounded" (the top-most band, e.g. "1,201+ learners").
  final int? maxStudents;
  final int amountUgx;
  final String currency;
  final int verifiedStudentCount;
  final DateTime countedAt;

  const StudentPricingSnapshot({
    required this.bandId,
    required this.minStudents,
    this.maxStudents,
    required this.amountUgx,
    required this.currency,
    required this.verifiedStudentCount,
    required this.countedAt,
  });

  @override
  List<Object?> get props => [
    bandId,
    minStudents,
    maxStudents,
    amountUgx,
    currency,
    verifiedStudentCount,
    countedAt,
  ];
}

/// One term's billing cycle. Doc ID is `${schoolId}_${termId}` (the
/// idempotency key that makes re-running confirmAcademicCalendar safe).
///
/// Stored top-level in `subscription_cycles` (tenant-scoped via [schoolId],
/// not nested under schools/{id}) - mirrors the payment_transactions
/// collection shape. Writable only by Cloud Functions; see
/// firestore.rules `match /subscription_cycles/{id}`.
class SubscriptionCycle extends Equatable {
  final String id;
  final String schoolId;

  /// Stand-in for a real `subscriptions` collection, which does not exist
  /// yet in this codebase - schools/{id} carries subscription fields
  /// directly (subscriptionPlanId, subscriptionExpiry, etc.) rather than
  /// pointing at a separate subscription document. Using schoolId here
  /// keeps the field meaningful without inventing a collection Phase 1
  /// doesn't need; Phase 2 can repoint this once/if a real subscriptions
  /// collection is introduced.
  final String subscriptionId;

  final String academicYearId;
  final String termId;
  final int termNumber;
  final DateTime termStart;
  final DateTime termEnd;

  /// Null until Phase 2's invoicing lands.
  final DateTime? invoiceIssuedAt;

  final DateTime paymentDueAt;
  final DateTime graceEndsAt;

  /// Null on every cycle generated by Phase 3A+ Cloud Functions - kept only
  /// so historical pre-Phase-3A cycle docs (which always had one) remain
  /// readable. See [pricingSnapshot] for the current pricing source.
  final SubscriptionPlanSnapshot? planSnapshot;

  /// The verified-student-count pricing band snapshot this cycle was billed
  /// against (Phase 3A+). Null when the school's verified student count did
  /// not unambiguously match exactly one active pricing band at generation
  /// time - see [pricingReviewRequired]/[pricingReviewReason] for why.
  final StudentPricingSnapshot? pricingSnapshot;

  /// True when this cycle could not be auto-priced against
  /// `student_pricing_bands` (e.g. no band covers the verified student
  /// count, or more than one band ambiguously matches) and needs a Super
  /// Admin/owner to resolve it manually.
  final bool pricingReviewRequired;

  /// Human-readable reason set alongside [pricingReviewRequired] - null when
  /// review isn't required.
  final String? pricingReviewReason;

  /// Discount snapshot - always null in Phase 1 (no discount engine yet).
  final Map<String, dynamic>? discountSnapshot;

  final SubscriptionCyclePaymentStatus paymentStatus;
  final SubscriptionCycleStatus cycleStatus;

  final DateTime? createdAt;
  final DateTime? updatedAt;

  const SubscriptionCycle({
    required this.id,
    required this.schoolId,
    required this.subscriptionId,
    required this.academicYearId,
    required this.termId,
    required this.termNumber,
    required this.termStart,
    required this.termEnd,
    this.invoiceIssuedAt,
    required this.paymentDueAt,
    required this.graceEndsAt,
    this.planSnapshot,
    this.pricingSnapshot,
    this.pricingReviewRequired = false,
    this.pricingReviewReason,
    this.discountSnapshot,
    this.paymentStatus = SubscriptionCyclePaymentStatus.unpaid,
    this.cycleStatus = SubscriptionCycleStatus.upcoming,
    this.createdAt,
    this.updatedAt,
  });

  @override
  List<Object?> get props => [
    id,
    schoolId,
    subscriptionId,
    academicYearId,
    termId,
    termNumber,
    termStart,
    termEnd,
    invoiceIssuedAt,
    paymentDueAt,
    graceEndsAt,
    planSnapshot,
    pricingSnapshot,
    pricingReviewRequired,
    pricingReviewReason,
    discountSnapshot,
    paymentStatus,
    cycleStatus,
    createdAt,
    updatedAt,
  ];
}
