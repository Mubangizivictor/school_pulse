import 'package:flutter/material.dart';
import 'package:flutter_bloc/flutter_bloc.dart';
import '../bloc/stores_assets_bloc.dart';
import '../bloc/stores_assets_event.dart';
import '../../domain/entities/inventory_item.dart';
import '../../domain/entities/stock_adjustment.dart';

class ReceiveGoodsDialog extends StatefulWidget {
  final InventoryItem item;
  const ReceiveGoodsDialog({super.key, required this.item});

  @override
  State<ReceiveGoodsDialog> createState() => _ReceiveGoodsDialogState();
}

class _ReceiveGoodsDialogState extends State<ReceiveGoodsDialog> {
  final _formKey = GlobalKey<FormState>();
  final _quantityController = TextEditingController();
  final _noteController = TextEditingController();

  @override
  void dispose() {
    _quantityController.dispose();
    _noteController.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return AlertDialog(
      title: Text('Receive ${widget.item.name}'),
      content: SingleChildScrollView(
        child: Form(
          key: _formKey,
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              Text(
                'Current Quantity: ${widget.item.quantity} ${widget.item.unit}',
              ),
              const SizedBox(height: 16),
              TextFormField(
                controller: _quantityController,
                decoration: const InputDecoration(
                  labelText: 'Quantity Received',
                ),
                keyboardType: TextInputType.number,
                validator: (value) {
                  if (value == null || int.tryParse(value) == null) {
                    return 'Invalid';
                  }
                  if (int.parse(value) <= 0) return 'Must be > 0';
                  return null;
                },
              ),
              TextFormField(
                controller: _noteController,
                decoration: const InputDecoration(
                  labelText: 'Notes (e.g., Supplier, Invoice #)',
                ),
                validator: (value) =>
                    value == null || value.isEmpty ? 'Required' : null,
              ),
            ],
          ),
        ),
      ),
      actions: [
        TextButton(
          onPressed: () => Navigator.pop(context),
          child: const Text('Cancel'),
        ),
        ElevatedButton(onPressed: _submit, child: const Text('Add to Stock')),
      ],
    );
  }

  void _submit() {
    if (_formKey.currentState!.validate()) {
      final adjustment = StockAdjustment(
        id: '', // Generated by repo
        itemId: widget.item.id,
        itemName: widget.item.name,
        quantityAdjusted: int.parse(_quantityController.text),
        reason: AdjustmentReason.other,
        notes: _noteController.text,
        date: DateTime.now(),
        adjustedBy: 'Current User',
      );

      context.read<StoresAssetsBloc>().add(AdjustStockRequested(adjustment));
      Navigator.pop(context);
    }
  }
}
