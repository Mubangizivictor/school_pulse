import 'package:flutter_bloc/flutter_bloc.dart';
import '../../domain/repositories/library_repository.dart';
import '../../domain/entities/library_book.dart';
import 'library_event.dart';
import 'library_state.dart';

class LibraryBloc extends Bloc<LibraryEvent, LibraryState> {
  final LibraryRepository repository;

  LibraryBloc({required this.repository}) : super(LibraryInitial()) {
    on<FetchBorrowedBooks>(_onFetchBorrowedBooks);
    on<LoadLibraryBooks>(_onLoadLibraryBooks);
    on<IssueBookRequested>(_onIssueBookRequested);
    on<ReturnBookRequested>(_onReturnBookRequested);
  }

  Future<void> _onFetchBorrowedBooks(FetchBorrowedBooks event, Emitter<LibraryState> emit) async {
    emit(LibraryLoading());
    final result = await repository.getBorrowedBooks(event.studentId);
    result.fold(
      (failure) => emit(const LibraryError('Server Failure')),
      (books) => emit(LibraryLoaded(books)),
    );
  }

  Future<void> _onLoadLibraryBooks(LoadLibraryBooks event, Emitter<LibraryState> emit) async {
    emit(LibraryLoading());
    final result = await repository.getAllBorrowedBooks();
    result.fold(
      (failure) => emit(const LibraryError('Server Failure')),
      (books) => emit(LibraryLoaded(books)),
    );
  }

  Future<void> _onIssueBookRequested(IssueBookRequested event, Emitter<LibraryState> emit) async {
    emit(LibraryLoading());
    final book = LibraryBook(
      id: '', // Generated by remote
      studentId: event.studentId,
      title: event.title,
      author: event.author,
      dueDate: event.dueDate,
    );
    final result = await repository.issueBook(book);
    result.fold(
      (failure) => emit(const LibraryError('Failed to issue book')),
      (_) => emit(const BookActionSuccess('Book issued successfully')),
    );
  }

  Future<void> _onReturnBookRequested(ReturnBookRequested event, Emitter<LibraryState> emit) async {
    emit(LibraryLoading());
    final result = await repository.returnBook(event.bookId);
    result.fold(
      (failure) => emit(const LibraryError('Failed to return book')),
      (_) => emit(const BookActionSuccess('Book returned successfully')),
    );
  }
}
